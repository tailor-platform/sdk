import { describe, expect, test } from "vitest";
import { db } from "#/configure/services/tailordb/index";
import { parseTypes } from "#/parser/service/tailordb/index";
import { toSchemaOutput } from "#/utils/test/internal";
import { generateUnifiedEnumConstants } from "./generate-enum-constants";
import { processEnumType } from "./process-enum-type";
import { enumConstantsPlugin, EnumConstantsGeneratorID } from "./index";
import type { TailorDBType } from "#/parser/service/tailordb/types";
import type { TailorDBTypeRaw as TailorDBTypeSchemaOutput } from "#/types/tailordb.generated";
import type { EnumDefinition } from "./types";

function parseTailorDBType(type: TailorDBTypeSchemaOutput): TailorDBType {
  const types = parseTypes({ [type.name]: type }, "test", {});
  return types[type.name]!;
}

describe("EnumConstantsPlugin", () => {
  const testDistPath = "/test/dist/enums.ts";

  describe("basic properties", () => {
    test("should have correct id and description", () => {
      const plugin = enumConstantsPlugin({ distPath: testDistPath });
      expect(plugin.id).toBe(EnumConstantsGeneratorID);
      expect(plugin.description).toBe("Generates enum constants from TailorDB table definitions");
    });
  });

  test.each<[string, [string, string]]>([
    ["different values", ["PENDING", "SHIPPED"]],
    ["identical values", ["OPEN", "CLOSED"]],
  ])("should reject colliding table and field names with %s", async (_, values) => {
    const order = parseTailorDBType(
      toSchemaOutput(db.table("Order", { itemStatus: db.enum(["OPEN", "CLOSED"]) })),
    );
    const orderItem = parseTailorDBType(
      toSchemaOutput(db.table("OrderItem", { status: db.enum(values) })),
    );
    const plugin = enumConstantsPlugin({ distPath: testDistPath });

    await expect(
      plugin.onTailorDBReady!({
        tailordb: [
          {
            namespace: "test",
            tables: { Order: order, OrderItem: orderItem },
            sourceInfo: new Map(),
            pluginAttachments: new Map(),
          },
        ],
        baseDir: "/test",
        configPath: "/test/tailor.config.ts",
        pluginConfig: { distPath: testDistPath },
      }),
    ).rejects.toThrow(
      'Enum constant "OrderItemStatus" is generated by both Order.itemStatus and OrderItem.status.',
    );
  });

  describe("enum collection", () => {
    test("should collect top-level enum fields", async () => {
      const type = db.table("User", {
        role: db.enum(["ADMIN", "USER"]),
        status: db.enum(["ACTIVE", "INACTIVE"], { optional: true }),
      });

      const result = await processEnumType(parseTailorDBType(toSchemaOutput(type)));

      expect(result.enums).toHaveLength(2);
      expect(result.enums[0]!.name).toBe("UserRole");
      expect(result.enums[0]!.source).toBe("User.role");
      expect(result.enums[0]!.values).toEqual([
        { value: "ADMIN", description: "" },
        { value: "USER", description: "" },
      ]);
      expect(result.enums[1]!.name).toBe("UserStatus");
      expect(result.enums[1]!.values).toEqual([
        { value: "ACTIVE", description: "" },
        { value: "INACTIVE", description: "" },
      ]);
    });

    test("should collect enum fields from nested objects", async () => {
      const type = db.table("PurchaseOrder", {
        attachedFiles: db.object(
          {
            id: db.uuid(),
            name: db.string(),
            type: db.enum(["text", "image"]),
          },
          { array: true },
        ),
      });

      const result = await processEnumType(parseTailorDBType(toSchemaOutput(type)));

      expect(result.enums).toHaveLength(1);
      expect(result.enums[0]!.name).toBe("PurchaseOrderAttachedFilesType");
      expect(result.enums[0]!.source).toBe("PurchaseOrder.attachedFiles.type");
      expect(result.enums[0]!.values).toEqual([
        { value: "text", description: "" },
        { value: "image", description: "" },
      ]);
    });

    test("should return empty array when no enums are present", async () => {
      const type = db.table("User", {
        name: db.string(),
        age: db.int(),
      });

      const result = await processEnumType(parseTailorDBType(toSchemaOutput(type)));

      expect(result.enums).toEqual([]);
    });

    test("should collect enum values with descriptions", async () => {
      const type = db.table("Invoice", {
        status: db.enum([
          { value: "draft", description: "Draft invoice" },
          { value: "sent", description: "Sent invoice" },
          "paid",
        ]),
      });

      const result = await processEnumType(parseTailorDBType(toSchemaOutput(type)));

      expect(result.enums).toHaveLength(1);
      expect(result.enums[0]!.name).toBe("InvoiceStatus");
      expect(result.enums[0]!.values).toEqual([
        { value: "draft", description: "Draft invoice" },
        { value: "sent", description: "Sent invoice" },
        { value: "paid", description: "" },
      ]);
    });
  });

  describe("generateUnifiedEnumConstants", () => {
    test("should generate enum constants in as const format", () => {
      const allEnums = [
        {
          name: "UserRole",
          source: "User.role",
          values: [{ value: "admin" }, { value: "user" }],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain("export const UserRole = {");
      expect(result).toContain('  "admin": "admin"');
      expect(result).toContain('  "user": "user"');
      expect(result).toContain("} as const;");
      expect(result).toContain("export type UserRole = (typeof UserRole)[keyof typeof UserRole];");
    });

    test("should preserve original enum values", () => {
      const allEnums = [
        {
          name: "InvoiceStatus",
          source: "Invoice.status",
          values: [{ value: "draft" }, { value: "sent" }, { value: "paid" }],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain('  "draft": "draft"');
      expect(result).toContain('  "sent": "sent"');
      expect(result).toContain('  "paid": "paid"');
    });

    test("should handle enum values with hyphens and spaces", () => {
      const allEnums = [
        {
          name: "OrderStatus",
          source: "Order.status",
          values: [{ value: "in-progress" }, { value: "ready to ship" }, { value: "delivered" }],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain('  "in_progress": "in-progress"');
      expect(result).toContain('  "ready_to_ship": "ready to ship"');
      expect(result).toContain('  "delivered": "delivered"');
    });

    test("should return empty string when no enums are present", () => {
      const allEnums: EnumDefinition[] = [];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toBe("");
    });

    test("should handle multiple enums", () => {
      const allEnums = [
        {
          name: "UserRole",
          source: "User.role",
          values: [{ value: "admin" }, { value: "user" }],
        },
        {
          name: "InvoiceStatus",
          source: "Invoice.status",
          values: [{ value: "draft" }, { value: "sent" }],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain("export const UserRole = {");
      expect(result).toContain("export const InvoiceStatus = {");
    });

    test("should generate JSDoc comments for enums with descriptions", () => {
      const allEnums = [
        {
          name: "InvoiceStatus",
          source: "Invoice.status",
          values: [
            { value: "draft", description: "Draft invoice" },
            { value: "sent", description: "Sent invoice" },
            { value: "paid", description: "Paid invoice" },
          ],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain("/**");
      expect(result).toContain(" * @property draft - Draft invoice");
      expect(result).toContain(" * @property sent - Sent invoice");
      expect(result).toContain(" * @property paid - Paid invoice");
      expect(result).toContain(" */");
      expect(result).toContain("export const InvoiceStatus = {");
    });

    test("should not generate JSDoc comments when no descriptions are present", () => {
      const allEnums = [
        {
          name: "UserRole",
          source: "User.role",
          values: [{ value: "admin" }, { value: "user" }],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).not.toContain("/**");
      expect(result).not.toContain("@property");
      expect(result).toContain("export const UserRole = {");
    });

    test("should only include @property for values with descriptions", () => {
      const allEnums = [
        {
          name: "InvoiceStatus",
          source: "Invoice.status",
          values: [
            { value: "draft", description: "Draft invoice" },
            { value: "sent" },
            { value: "paid", description: "Paid invoice" },
          ],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain("/**");
      expect(result).toContain(" * @property draft - Draft invoice");
      expect(result).toContain(" * @property sent");
      expect(result).toContain(" * @property paid - Paid invoice");
      expect(result).toContain(" */");
      expect(result).toContain("export const InvoiceStatus = {");
    });

    test("should include field description at the top of JSDoc", () => {
      const allEnums = [
        {
          name: "InvoiceStatus",
          source: "Invoice.status",
          fieldDescription: "Invoice status",
          values: [
            { value: "draft", description: "Draft invoice" },
            { value: "sent" },
            { value: "paid", description: "Paid invoice" },
          ],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain("/**");
      expect(result).toContain(" * Invoice status");
      expect(result).toContain(" *");
      expect(result).toContain(" * @property draft - Draft invoice");
      expect(result).toContain(" * @property sent");
      expect(result).toContain(" * @property paid - Paid invoice");
      expect(result).toContain(" */");
    });

    test("should only show field description when no value descriptions exist", () => {
      const allEnums = [
        {
          name: "UserRole",
          source: "User.role",
          fieldDescription: "User role",
          values: [{ value: "admin" }, { value: "user" }],
        },
      ];

      const result = generateUnifiedEnumConstants(allEnums);

      expect(result).toContain("/**");
      expect(result).toContain(" * User role");
      expect(result).toContain(" */");
      expect(result).not.toContain(" * @property");
    });

    test("should reject duplicate enum names", () => {
      const allEnums = [
        { name: "OrderItemStatus", source: "Order.itemStatus", values: [{ value: "OPEN" }] },
        { name: "OrderItemStatus", source: "OrderItem.status", values: [{ value: "PENDING" }] },
      ];

      expect(() => generateUnifiedEnumConstants(allEnums)).toThrow(
        'Enum constant "OrderItemStatus" is generated by both Order.itemStatus and OrderItem.status.',
      );
    });
  });
});

import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as path from "pathe";
import { logger } from "@/cli/shared/logger";
import { isPluginGeneratedType } from "@/types/tailordb";
import type {
  TailorDbErdColumn,
  TailorDbErdColumnRelation,
  TailorDbErdIndex,
  TailorDbErdRelation,
  TailorDbErdRelationship,
  TailorDbErdSchema,
  TailorDbErdSource,
  TailorDbErdTable,
  TailorDbErdTypeSource,
} from "./types";
import type { TailorDBNamespaceData } from "@/types/plugin-generation";
import type {
  OperatorFieldConfig,
  ParsedField,
  TailorDBType,
  TypeSourceInfoEntry,
} from "@/types/tailordb";

const CLEAN_ROOM_NOTES = [
  "Generated by a TailorDB-specific viewer implementation.",
  "The implementation is based on TailorDB schema contracts, public Liam documentation, Liam CLI help, and black-box generated-output observation.",
  "It does not copy Liam source code, generated JavaScript/CSS, parser internals, or layout internals.",
];

interface BuildTailorDbErdSchemaOptions {
  namespaceData: TailorDBNamespaceData;
  generatedAt?: string;
  source?: TailorDbErdSource;
}

interface WriteTailorDbErdSchemaOptions {
  schema: TailorDbErdSchema;
  outputPath: string;
}

interface BuildColumnOptions {
  fieldName: string;
  fieldConfig: OperatorFieldConfig;
  parsedField?: ParsedField;
  indexEntries: Array<[string, TailorDbErdIndex]>;
}

function buildRevision(schema: Omit<TailorDbErdSchema, "generatedAt" | "revision">): string {
  return createHash("sha256").update(JSON.stringify(schema)).digest("hex").slice(0, 16);
}

function toTypeSource(source: TypeSourceInfoEntry | undefined): TailorDbErdTypeSource | undefined {
  if (!source) return undefined;
  if (isPluginGeneratedType(source)) {
    return {
      kind: "plugin",
      exportName: source.exportName,
      pluginId: source.pluginId,
      pluginImportPath: source.pluginImportPath,
      originalExportName: source.originalExportName,
      generatedTypeKind: source.generatedTypeKind,
      namespace: source.namespace,
    };
  }
  return {
    kind: "user",
    exportName: source.exportName,
  };
}

function toRelationships(
  relationships: Record<string, TailorDBType["forwardRelationships"][string]>,
): TailorDbErdRelationship[] {
  return Object.entries(relationships)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, relationship]) => ({
      name,
      targetType: relationship.targetType,
      targetField: relationship.targetField,
      sourceField: relationship.sourceField,
      isArray: relationship.isArray,
      ...(relationship.description && { description: relationship.description }),
    }));
}

function toIndexes(type: TailorDBType): TailorDbErdIndex[] {
  return Object.entries(type.indexes ?? {})
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, index]) => ({
      name,
      fields: [...index.fields],
      unique: index.unique === true,
    }));
}

function toColumnRelation(options: BuildColumnOptions): TailorDbErdColumnRelation | undefined {
  const { fieldConfig, parsedField } = options;
  if (!fieldConfig.foreignKey || !fieldConfig.foreignKeyType) {
    return undefined;
  }

  const required = fieldConfig.required !== false;
  const kind = parsedField?.relation || fieldConfig.rawRelation ? "relation" : "foreignKey";
  return {
    targetTable: fieldConfig.foreignKeyType,
    targetColumn: fieldConfig.foreignKeyField || "id",
    kind,
    required,
    ...(fieldConfig.rawRelation?.type && { relationType: fieldConfig.rawRelation.type }),
    ...(parsedField?.relation?.forwardName && { forwardName: parsedField.relation.forwardName }),
    ...(parsedField?.relation?.backwardName && {
      backwardName: parsedField.relation.backwardName,
    }),
  };
}

function toColumn(options: BuildColumnOptions): TailorDbErdColumn {
  const { fieldName, fieldConfig } = options;
  const indexNames = options.indexEntries
    .filter(([, index]) => index.fields.includes(fieldName))
    .map(([name]) => name);
  const uniqueIndexNames = options.indexEntries
    .filter(([, index]) => index.unique && index.fields.includes(fieldName))
    .map(([name]) => name);

  const enumValues = fieldConfig.allowedValues?.map((value) => value.value) ?? [];
  const enumValueDescriptions = Object.fromEntries(
    (fieldConfig.allowedValues ?? []).flatMap((value) =>
      value.description ? [[value.value, value.description]] : [],
    ),
  );
  const nestedFields = Object.entries(fieldConfig.fields ?? {}).map(([nestedName, nestedConfig]) =>
    toColumn({
      fieldName: nestedName,
      fieldConfig: nestedConfig,
      indexEntries: [],
    }),
  );
  const relation = toColumnRelation(options);

  return {
    name: fieldName,
    type: fieldConfig.type || "string",
    required: fieldConfig.required !== false,
    array: fieldConfig.array === true,
    ...(fieldConfig.description && { description: fieldConfig.description }),
    ...(fieldConfig.unique && { unique: true }),
    ...((fieldConfig.index || indexNames.length > 0) && { index: true }),
    ...(indexNames.length > 0 && { indexNames }),
    ...(uniqueIndexNames.length > 0 && { uniqueIndexNames }),
    ...(enumValues.length > 0 && { enumValues }),
    ...(Object.keys(enumValueDescriptions).length > 0 && { enumValueDescriptions }),
    ...(fieldConfig.vector && { vector: true }),
    ...(fieldConfig.serial && { serial: { ...fieldConfig.serial } }),
    ...(fieldConfig.scale !== undefined && { scale: fieldConfig.scale }),
    ...(fieldConfig.validate?.length && { validations: fieldConfig.validate.length }),
    ...(fieldConfig.hooks && {
      hooks: {
        ...(fieldConfig.hooks.create && { create: true }),
        ...(fieldConfig.hooks.update && { update: true }),
      },
    }),
    ...(nestedFields.length > 0 && { fields: nestedFields }),
    ...(relation && { relation }),
  };
}

function toTable(type: TailorDBType, source: TypeSourceInfoEntry | undefined): TailorDbErdTable {
  const indexes = toIndexes(type);
  const indexEntries: Array<[string, TailorDbErdIndex]> = indexes.map((index) => [
    index.name,
    index,
  ]);
  const fieldColumns = Object.entries(type.fields).map(([fieldName, field]) =>
    toColumn({
      fieldName,
      fieldConfig: field.config,
      parsedField: field,
      indexEntries,
    }),
  );

  return {
    name: type.name,
    pluralForm: type.pluralForm,
    ...(type.description && { description: type.description }),
    ...(toTypeSource(source) && { source: toTypeSource(source) }),
    columns: [
      {
        name: "id",
        type: "uuid",
        required: true,
        array: false,
        primaryKey: true,
        unique: true,
      },
      ...fieldColumns,
    ],
    indexes,
    forwardRelationships: toRelationships(type.forwardRelationships),
    backwardRelationships: toRelationships(type.backwardRelationships),
  };
}

function toRelation(sourceTable: string, field: ParsedField): TailorDbErdRelation | undefined {
  const relation = toColumnRelation({
    fieldName: field.name,
    fieldConfig: field.config,
    parsedField: field,
    indexEntries: [],
  });
  if (!relation) return undefined;

  return {
    name: `${sourceTable}.${field.name}->${relation.targetTable}.${relation.targetColumn}`,
    sourceTable,
    sourceColumns: [field.name],
    targetTable: relation.targetTable,
    targetColumns: [relation.targetColumn],
    required: relation.required,
    unique: field.config.unique === true || field.relation?.unique === true,
    kind: relation.kind,
    ...(relation.relationType && { relationType: relation.relationType }),
    ...(relation.forwardName && { forwardName: relation.forwardName }),
    ...(relation.backwardName && { backwardName: relation.backwardName }),
  };
}

function buildRelations(types: Record<string, TailorDBType>): TailorDbErdRelation[] {
  const relations: TailorDbErdRelation[] = [];
  for (const type of Object.values(types)) {
    for (const field of Object.values(type.fields)) {
      const relation = toRelation(type.name, field);
      if (relation) {
        relations.push(relation);
      }
    }
  }
  return relations.sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Build the TailorDB ERD viewer schema for one namespace.
 * @param options - Schema build options.
 * @returns TailorDB ERD viewer schema.
 */
export function buildTailorDbErdSchema(options: BuildTailorDbErdSchemaOptions): TailorDbErdSchema {
  const { namespaceData } = options;
  const tables = Object.values(namespaceData.types)
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((type) => toTable(type, namespaceData.sourceInfo.get(type.name)));

  const schemaWithoutRevision = {
    version: 1 as const,
    namespace: namespaceData.namespace,
    source: options.source ?? "local",
    cleanRoom: {
      implementation: "tailor-sdk" as const,
      notes: CLEAN_ROOM_NOTES,
    },
    tables,
    relations: buildRelations(namespaceData.types),
  };

  return {
    ...schemaWithoutRevision,
    generatedAt: options.generatedAt ?? new Date().toISOString(),
    revision: buildRevision(schemaWithoutRevision),
  };
}

/**
 * Writes a TailorDB ERD viewer schema to disk.
 * @param options - Schema write options.
 */
export function writeTailorDbErdSchemaToFile(options: WriteTailorDbErdSchemaOptions): void {
  const json = JSON.stringify(options.schema, null, 2);
  fs.mkdirSync(path.dirname(options.outputPath), { recursive: true });
  fs.writeFileSync(options.outputPath, json, "utf8");

  const relativePath = path.relative(process.cwd(), options.outputPath);
  logger.success(`Wrote ERD schema to ${relativePath}`);
}

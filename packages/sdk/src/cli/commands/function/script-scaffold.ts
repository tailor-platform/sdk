/**
 * Scaffolding helpers for the `tailor function script` command.
 *
 * A scaffolded one-off script is a plain default-exported function that
 * `tailor function run` executes on the platform without deploying. When the
 * project does not configure `kyselyTypePlugin`, the scaffold also writes a
 * script-scoped `db.ts` generated from local table definitions by default, plus a
 * `db.snapshot.json` snapshot that `function run` checks for schema drift.
 */


import * as fs from "node:fs";
import { createFilesMatcher, getTsconfig } from "get-tsconfig";
import * as path from "pathe";
import type { AppConfig } from "#/configure/config/types";

type DateRepresentation = AppConfig["defaultDateRepresentation"];

/**
 * Another generated `tailor.d.ts` whose `defaultDateRepresentation` differs.
 */
type DateRepresentationConflict = {
  /** Absolute path of the other `tailor.d.ts` */
  file: string;
  /** The representation it declares, or undefined when unset */
  representation: DateRepresentation;
};

/**
 * The tsconfig that includes a `tailor.d.ts`, and the generated files in it that disagree.
 */
export type DateRepresentationConflicts = {
  /** Absolute path of the tsconfig including the `tailor.d.ts` */
  tsconfigPath: string;
  /** Generated `tailor.d.ts` files in that tsconfig declaring a different default */
  conflicts: DateRepresentationConflict[];
};

const GENERATED_HEADER = "// This file is auto-generated by @tailor-platform/sdk";
const REGISTRY_PATTERN = /interface DateRepresentationRegistry \{\s*(?:default: "(\w+)";\s*)?\}/;

function declaredRepresentation(content: string): DateRepresentation | null {
  if (!content.startsWith(GENERATED_HEADER)) return null;
  return REGISTRY_PATTERN.exec(content)?.[1] as DateRepresentation;
}

function readGenerated(file: string): DateRepresentation | null {
  try {
    return declaredRepresentation(fs.readFileSync(file, "utf8"));
  } catch {
    return null;
  }
}

/**
 * Find generated `tailor.d.ts` files that share a tsconfig with `dtsPath` but
 * declare a different `defaultDateRepresentation`. Their augmentations merge
 * into one program, so the field types could not match every application.
 * @param dtsPath - Absolute path the `tailor.d.ts` is about to be written to
 * @param representation - The config's `defaultDateRepresentation`
 * @returns The including tsconfig and the conflicts, or undefined when no tsconfig includes `dtsPath`
 */
export function findDateRepresentationConflicts(
  dtsPath: string,
  representation: DateRepresentation,
): DateRepresentationConflicts | undefined {
  const target = path.resolve(dtsPath);
  const tsconfig = getTsconfig(target, "tsconfig.json", new Map(), true);
  if (!tsconfig) return undefined;
  const includes = createFilesMatcher(tsconfig);
  const root = path.dirname(tsconfig.path);
  const conflicts = fs
    .globSync("**/*.d.ts", {
      cwd: root,
      exclude: (entry) => entry === "node_modules" || entry.endsWith("/node_modules"),
    })
    .map((relative) => path.join(root, relative))
    .filter((file) => file !== target && includes(file))
    .flatMap((file) => {
      const declared = readGenerated(file);
      return declared === null || declared === representation
        ? []
        : [{ file, representation: declared }];
    });
  return { tsconfigPath: tsconfig.path, conflicts };
}

import { describe, it, expect } from "vitest";
import { generateGqlSchemaDts } from "./generate-dts";
import type { GqlSchemaTypeMetadata } from "./types";

describe("generateGqlSchemaDts", () => {
  it("generates correct declaration file from type metadata", () => {
    const types: GqlSchemaTypeMetadata[] = [
      {
        name: "User",
        entries: [
          {
            operationName: "user",
            variablesExpr: "{ id: string }",
            resultExpr:
              '{ user: InferGqlResult<(typeof import("./tailordb/user"))["user"]> | null }',
          },
          {
            operationName: "users",
            variablesExpr: "Record<string, unknown>",
            resultExpr:
              '{ users: { collection: InferGqlResult<(typeof import("./tailordb/user"))["user"]>[] } }',
          },
          {
            operationName: "createUser",
            variablesExpr:
              '{ input: InferCreateInput<(typeof import("./tailordb/user"))["user"]> }',
            resultExpr:
              '{ createUser: InferGqlResult<(typeof import("./tailordb/user"))["user"]> }',
          },
        ],
      },
    ];

    const result = generateGqlSchemaDts(types);

    expect(result).toContain("// Auto-generated by @tailor-platform/graphql-schema");
    expect(result).toContain("// Do not edit this file manually.");
    expect(result).toContain(
      'import type { InferCreateInput, InferUpdateInput, InferGqlResult } from "@tailor-platform/sdk/graphql";',
    );
    expect(result).toContain('declare module "@tailor-platform/sdk/graphql" {');
    expect(result).toContain("  interface GeneratedGqlSchema {");
    expect(result).toContain("    user: {");
    expect(result).toContain("      variables: { id: string };");
    expect(result).toContain("    users: {");
    expect(result).toContain("    createUser: {");
    expect(result).toContain("  interface GeneratedGqlTypeNames {");
    expect(result).toContain("    UserCreateInput: true;");
    expect(result).toContain("  }");
    expect(result).toContain("}");
  });

  it("returns empty string when no entries exist", () => {
    const result = generateGqlSchemaDts([]);
    expect(result).toBe("");
  });

  it("returns empty string when all types have no entries", () => {
    const types: GqlSchemaTypeMetadata[] = [{ name: "Empty", entries: [] }];
    const result = generateGqlSchemaDts(types);
    expect(result).toBe("");
  });

  it("combines entries from multiple types", () => {
    const types: GqlSchemaTypeMetadata[] = [
      {
        name: "User",
        entries: [
          {
            operationName: "createUser",
            variablesExpr: "{ input: InferCreateInput<TypeRef> }",
            resultExpr: "{ createUser: InferGqlResult<TypeRef> }",
          },
        ],
      },
      {
        name: "Post",
        entries: [
          {
            operationName: "createPost",
            variablesExpr: "{ input: InferCreateInput<TypeRef> }",
            resultExpr: "{ createPost: InferGqlResult<TypeRef> }",
          },
        ],
      },
    ];

    const result = generateGqlSchemaDts(types);
    expect(result).toContain("    createUser: {");
    expect(result).toContain("    createPost: {");
  });

  it("generates GeneratedGqlTypeNames with create and update input types", () => {
    const types: GqlSchemaTypeMetadata[] = [
      {
        name: "User",
        entries: [
          {
            operationName: "createUser",
            variablesExpr: "{ input: InferCreateInput<TypeRef> }",
            resultExpr: "{ createUser: InferGqlResult<TypeRef> }",
          },
          {
            operationName: "updateUser",
            variablesExpr: "{ id: string; input: InferUpdateInput<TypeRef> }",
            resultExpr: "{ updateUser: InferGqlResult<TypeRef> }",
          },
        ],
      },
    ];

    const result = generateGqlSchemaDts(types);
    expect(result).toContain("  interface GeneratedGqlTypeNames {");
    expect(result).toContain("    UserCreateInput: true;");
    expect(result).toContain("    UserUpdateInput: true;");
  });

  it("does not generate GeneratedGqlTypeNames when only read/delete entries", () => {
    const types: GqlSchemaTypeMetadata[] = [
      {
        name: "User",
        entries: [
          {
            operationName: "user",
            variablesExpr: "{ id: string }",
            resultExpr: "{ user: InferGqlResult<TypeRef> | null }",
          },
          {
            operationName: "deleteUser",
            variablesExpr: "{ id: string }",
            resultExpr: "{ deleteUser: { id: string } }",
          },
        ],
      },
    ];

    const result = generateGqlSchemaDts(types);
    expect(result).not.toContain("GeneratedGqlTypeNames");
  });
});

import * as fs from "node:fs";
import { logger, styles, prompt } from "@tailor-platform/sdk/cli";
import { resolveWithinRoot } from "./check";
import {
  AUTOFIX_LABEL,
  LOCK_VERSION,
  readManagedLock,
  targetWorkflows,
  writeLock,
  type LockFile,
} from "./lock";

export type DeleteOptions = {
  /** Repo-relative paths to managed workflow files, as printed by `setup <target>`. */
  files: string[];
  /** Skip the confirmation prompt. */
  yes: boolean;
  outputDir: string;
};

// Mirrors the --dir normalization in generate.ts's resolve(): POSIX separators,
// collapsed duplicate slashes, no leading "./" or trailing "/", so a path typed
// with either style still matches the posix-normalized `file` recorded in the lock.
function normalizeRelPath(input: string): string {
  return input
    .replaceAll("\\", "/")
    .replace(/\/{2,}/g, "/")
    .replace(/^\.\//, "")
    .replace(/\/$/, "");
}

type Match = { relPath: string; absPath: string; label: string };

function ownerOf(lock: LockFile, relPath: string): { label: string; files: string[] } | undefined {
  const target = lock.targets.find((t) =>
    targetWorkflows(t).some((workflow) => workflow.file === relPath),
  );
  if (target) {
    return {
      label: `${target.kind} ${target.workspaceName}`,
      files: targetWorkflows(target).map((workflow) => workflow.file),
    };
  }
  return lock.autofix?.file === relPath ? { label: AUTOFIX_LABEL, files: [relPath] } : undefined;
}

function resolveMatches(outputDir: string, lock: LockFile, input: string): Match[] {
  const relPath = normalizeRelPath(input);
  if (resolveWithinRoot(outputDir, relPath) === null) {
    throw new Error(`"${input}" must be a path inside the repository.`);
  }
  const owner = ownerOf(lock, relPath);
  if (owner === undefined) {
    throw new Error(
      `"${relPath}" is not a managed workflow file (not recorded in .github/tailor.lock). ` +
        "Only files generated by `tailor setup` can be deleted with this command.",
    );
  }
  return owner.files.map((file) => {
    const absPath = resolveWithinRoot(outputDir, file);
    if (absPath === null) {
      throw new Error(`"${file}" in .github/tailor.lock must be a path inside the repository.`);
    }
    return { relPath: file, absPath, label: owner.label };
  });
}

/**
 * Delete managed workflow files and their `.github/tailor.lock` entries.
 *
 * Refuses to touch files that are not recorded in the lock, so it never
 * deletes hand-written workflows.
 * @param options - Delete options
 */
export async function setupDelete(options: DeleteOptions): Promise<void> {
  const { outputDir, yes } = options;
  const lock = readManagedLock(outputDir);

  const relPaths = [...new Set(options.files.map(normalizeRelPath))];
  const matches = [
    ...new Map(
      relPaths
        .flatMap((relPath) => resolveMatches(outputDir, lock, relPath))
        .map((match) => [match.relPath, match]),
    ).values(),
  ];

  if (!yes) {
    const list = matches.map((m) => m.relPath).join("\n  ");
    const confirmed = await prompt.confirm({
      message:
        `This will delete the following file(s) and their .github/tailor.lock entries:\n  ${list}\n` +
        "Continue?",
      default: false,
    });
    if (!confirmed) {
      throw new Error("Delete cancelled. No files were changed.");
    }
  }

  const deleted = new Set<string>();
  try {
    for (const { relPath, absPath, label } of matches) {
      fs.rmSync(absPath, { force: true });
      deleted.add(relPath);
      logger.success(`Deleted ${styles.path(relPath)} (${label})`);
    }
  } finally {
    if (deleted.size > 0) {
      const { autofix, ...rest } = lock;
      writeLock(outputDir, {
        ...rest,
        version: LOCK_VERSION,
        targets: lock.targets.filter(
          (target) => !targetWorkflows(target).every((workflow) => deleted.has(workflow.file)),
        ),
        ...(autofix && !deleted.has(autofix.file) ? { autofix } : {}),
      });
    }
  }
}

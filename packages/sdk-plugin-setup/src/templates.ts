// Keep or drop a `# __X_START__` ... `# __X_END__` block (marker lines removed
// when kept, whole block removed when dropped).
function block(content: string, name: string, keep: boolean): string {
  if (keep) {
    return content.replace(new RegExp(`^ *# __${name}_(?:START|END)__\\n`, "gm"), "");
  }
  return content.replace(
    new RegExp(`^ *# __${name}_START__\\n[\\s\\S]*?^ *# __${name}_END__\\n`, "m"),
    "",
  );
}

// Replace a single-line `# __X__` marker. The marker line's own indentation is
// reused for the replacement; when `replacement` is undefined the whole line is
// removed. `replacement` may contain newlines for multi-line expansions.
function line(content: string, name: string, replacement: string | undefined): string {
  const re = new RegExp(`^([ \\t]*)# __${name}__\\n`, "gm");
  return content.replace(re, (_match, indent: string) => {
    if (replacement === undefined) return "";
    return (
      replacement
        .split("\n")
        .map((l) => (l ? indent + l : l))
        .join("\n") + "\n"
    );
  });
}

function configPathOf(dir: string): string {
  return dir === "." ? "tailor.config.ts" : `${dir}/tailor.config.ts`;
}

/**
 * Step id suffix for an app of a multi-directory target, derived from its directory.
 * @param dir - App directory relative to the repository root
 * @returns Suffix such as `apps-erp-backend` for `apps/erp/backend`
 */
export function appSlug(dir: string): string {
  return dir === "." ? "root" : dir.replaceAll(/[^A-Za-z0-9-]+/g, "-");
}

const ALL_ZERO_SHA = "0000000000000000000000000000000000000000";

export type WorkflowKind = "branch" | "tag" | "preview";

const WORKFLOW_FILE_SUFFIX: Record<WorkflowKind, string> = {
  branch: "",
  tag: "-tag",
  preview: "-preview",
};

/**
 * Path of the workflow a target generates. The kind is part of the name so a branch, tag, and
 * preview workflow can share a workspace name.
 * @param kind - Target kind
 * @param workspaceName - Workspace name the workflow is generated for
 * @returns Workflow file path relative to the repository root
 */
export function workflowFilePath(kind: WorkflowKind, workspaceName: string): string {
  return `.github/workflows/tailor-${workspaceName}${WORKFLOW_FILE_SUFFIX[kind]}.yml`;
}

function changePatterns(params: {
  workingDirectory?: string;
  apps?: RenderApp[];
  extraPaths?: string[];
  workflowFile: string;
}): string[] | undefined {
  const dirs = params.apps
    ? params.apps.map((app) => app.dir)
    : params.workingDirectory
      ? [params.workingDirectory]
      : [];
  if (dirs.length === 0 || dirs.includes(".")) return undefined;
  // Ahead of the extra paths: the last matching pattern decides, so a later `!` pattern can drop it.
  return [...dirs.map((dir) => `${dir}/**`), params.workflowFile, ...(params.extraPaths ?? [])];
}

function changesJob(patterns: readonly string[]): string {
  return [
    "tailor-changes:",
    "  runs-on: ubuntu-latest",
    "  timeout-minutes: 5",
    "  permissions:",
    "    contents: read",
    "  outputs:",
    "    relevant: ${{ steps.tailor-changes.outputs.relevant }}",
    "  steps:",
    "    - id: tailor-changes",
    `      uses: tailor-platform/actions/relevance@${ACTIONS_SHA} # ${ACTIONS_VERSION}`,
    "      with:",
    `        sha-base: \${{ github.event.pull_request.base.sha || github.event.before || '${ALL_ZERO_SHA}' }}`,
    "        sha-head: ${{ github.event.pull_request.head.sha || github.sha }}",
    "        path-patterns: |",
    ...patterns.map((pattern) => `          ${pattern}`),
    "        github-token: ${{ github.token }}",
  ].join("\n");
}

// Gate a job's `if:` on the change detection job; skipped jobs report success,
// unlike a workflow that `on.paths` never started, so the checks stay requirable.
// A failed detection runs the job instead of skipping it: a job skipped after a
// failed `needs` also reports success and would let a required check pass.
function gateOnChanges(ifLine: string, patterns: readonly string[] | undefined): string {
  if (!patterns) return ifLine;
  const condition = ifLine.replace(/^if: (\|-\n)?/, "");
  const lines = condition.split("\n").map((l) => l.replace(/^ {2}/, ""));
  return [
    "needs: tailor-changes",
    "if: |-",
    "  !cancelled() && (",
    "    needs.tailor-changes.result != 'success' ||",
    "    needs.tailor-changes.outputs.relevant == 'true'",
    "  ) && (",
    ...lines.map((l) => `    ${l}`),
    "  )",
  ].join("\n");
}

function changesIds(patterns: readonly string[] | undefined): string[] {
  return patterns ? ["tailor-changes", "tailor-changes/tailor-changes"] : [];
}

function changesGuard(patterns: readonly string[] | undefined): string | undefined {
  if (!patterns) return undefined;
  return [
    "- id: tailor-changes-guard",
    "  if: needs.tailor-changes.result != 'success'",
    "  run: |",
    `    echo "::error::Change detection (tailor-changes) did not succeed; re-run the failed jobs."`,
    "    exit 1",
  ].join("\n");
}

function changesGuardIds(job: string, patterns: readonly string[] | undefined): string[] {
  return patterns ? [`${job}/tailor-changes-guard`] : [];
}

function perAppGenerateCheckSteps(apps: readonly RenderApp[]): string {
  return apps
    .flatMap((app) => [
      `- id: tailor-generate-check-${appSlug(app.dir)}`,
      `  uses: tailor-platform/actions/generate-check@${ACTIONS_SHA} # ${ACTIONS_VERSION}`,
      `  with:`,
      `    package-manager: __PACKAGE_MANAGER__`,
      ...(app.dir === "." ? [] : [`    working-directory: ${app.dir}`]),
    ])
    .join("\n");
}

function perAppSeedValidateSteps(apps: readonly RenderApp[]): string | undefined {
  const lines = apps
    .filter((app) => app.seedValidate)
    .flatMap((app) => [
      `- id: tailor-seed-validate-${appSlug(app.dir)}`,
      `  run: __TAILOR_CLI__ seed validate`,
      `  env:`,
      `    SEED_USER_PASSWORD: \${{ github.event_name == 'pull_request' && 'validate-only' || secrets.SEED_USER_PASSWORD }}`,
      ...(app.dir === "." ? [] : [`  working-directory: ${app.dir}`]),
    ]);
  return lines.length > 0 ? lines.join("\n") : undefined;
}

function perAppMigrationDriftCheckSteps(apps: readonly RenderApp[]): string | undefined {
  const lines = apps
    .filter((app) => app.migrationDriftCheck)
    .flatMap((app) => [
      `- id: tailor-migration-drift-check-${appSlug(app.dir)}`,
      `  uses: tailor-platform/actions/migration-drift-check@${ACTIONS_SHA} # ${ACTIONS_VERSION}`,
      `  with:`,
      `    package-manager: __PACKAGE_MANAGER__`,
      ...(app.dir === "." ? [] : [`    working-directory: ${app.dir}`]),
    ]);
  return lines.length > 0 ? lines.join("\n") : undefined;
}

function perAppIds(
  job: string,
  step: string,
  apps: readonly RenderApp[],
  include: (app: RenderApp) => boolean | undefined,
): string[] {
  return apps.filter(include).map((app) => `${job}/${step}-${appSlug(app.dir)}`);
}

function seedValidateIds(
  job: string,
  seedValidate: boolean,
  apps: readonly RenderApp[] | undefined,
): string[] {
  if (apps) return perAppIds(job, "tailor-seed-validate", apps, (app) => app.seedValidate);
  return seedValidate ? [`${job}/tailor-seed-validate`] : [];
}

function migrationDriftCheckIds(
  job: string,
  migrationDriftCheck: boolean,
  apps: readonly RenderApp[] | undefined,
): string[] {
  if (apps) {
    return perAppIds(job, "tailor-migration-drift-check", apps, (app) => app.migrationDriftCheck);
  }
  return migrationDriftCheck ? [`${job}/tailor-migration-drift-check`] : [];
}

// Dataset names are restricted to `[A-Za-z0-9_-]`, so they need no shell quoting.
function applySeed(content: string, seed: RenderSeed | undefined): string {
  const args = (seed?.datasets ?? []).map((dataset) => ` --dataset ${dataset}`).join("");
  const seeded = block(content, "SEED", seed !== undefined);
  return block(seeded, "SEED_PREFLIGHT", seed !== undefined)
    .replaceAll("__SEED_ARGS__", () => args)
    .replaceAll("__SEED_VALIDATE_ARGS__", () => `${seed ? " --upsert" : ""}${args}`);
}

function seedIds(job: string, seed: RenderSeed | undefined): string[] {
  return seed ? [`${job}/tailor-seed`] : [];
}

function generateCheckIds(job: string, apps: readonly RenderApp[] | undefined): string[] {
  return apps
    ? apps.map((app) => `${job}/tailor-generate-check-${appSlug(app.dir)}`)
    : [`${job}/tailor-generate-check`];
}

function applyCommon(
  content: string,
  params: {
    workspaceName: string;
    workingDirectory?: string;
    apps?: RenderApp[];
    environment: string;
    packageManager: PackageManager;
  },
): string {
  const { environment, packageManager, apps } = params;
  const workingDirectory = apps ? undefined : params.workingDirectory;
  let out = line(content, "HEADER", HEADER);
  out = block(out, "GENERATE_CHECK", apps === undefined);
  out = line(out, "PER_APP_GENERATE_CHECK", apps ? perAppGenerateCheckSteps(apps) : undefined);
  out = line(out, "PER_APP_SEED_VALIDATE", apps ? perAppSeedValidateSteps(apps) : undefined);
  out = line(
    out,
    "PER_APP_MIGRATION_DRIFT_CHECK",
    apps ? perAppMigrationDriftCheckSteps(apps) : undefined,
  );
  out = line(
    out,
    "CONFIG_ENV",
    apps
      ? `env:\n  TAILOR_CONFIG_PATH: ${apps.map((app) => configPathOf(app.dir)).join(",")}`
      : undefined,
  );
  out = line(
    out,
    "WORKING_DIRECTORY",
    workingDirectory ? `working-directory: ${workingDirectory}` : undefined,
  );
  // Plain placeholders last so values containing `$` are not interpreted as
  // replacement patterns.
  return out
    .replaceAll("__WORKSPACE_NAME__", () => params.workspaceName)
    .replaceAll("__ENVIRONMENT__", () => environment)
    .replaceAll("__PACKAGE_MANAGER__", () => packageManager)
    .replaceAll("__TAILOR_CLI__", () => TAILOR_CLI_COMMANDS[packageManager])
    .replaceAll("__APP_DIR__", () => workingDirectory ?? ".");
}

function branchDeployIf(restrictDispatch: boolean): string {
  const dispatch = restrictDispatch
    ? "(github.event_name == 'workflow_dispatch' && !inputs['dry-run'] && github.ref == 'refs/heads/__BRANCH__')"
    : "(github.event_name == 'workflow_dispatch' && !inputs['dry-run'])";
  return `if: |-\n  github.event_name == 'push' ||\n  ${dispatch}`;
}

function tagDeployGate(
  hasGuard: boolean,
  restrictDispatch: boolean,
): { needs: string; if: string } {
  if (!restrictDispatch) {
    return {
      needs: "needs: tailor-plan",
      if: `if: \${{ !(github.event_name == 'workflow_dispatch' && inputs['dry-run']) }}`,
    };
  }
  const conditions = [
    "!(github.event_name == 'workflow_dispatch' && inputs['dry-run'])",
    "startsWith(github.ref, 'refs/tags/')",
    ...(hasGuard ? ["needs.tailor-tag-guard.outputs.on-branch == 'true'"] : []),
  ];
  return {
    needs: hasGuard ? "needs: [tailor-tag-guard, tailor-plan]" : "needs: tailor-plan",
    if: `if: |-\n  ${conditions.join(" &&\n  ")}`,
  };
}

function appendResultJob(rendered: RenderResult, resultJob: string): RenderResult {
  const jobs = rendered.generatedIds.filter((id) => !id.includes("/"));
  return {
    content: line(rendered.content, "RESULT_NEEDS", jobs.map((job) => `- ${job}`).join("\n")),
    generatedIds: [...rendered.generatedIds, resultJob, `${resultJob}/${resultJob}`],
  };
}

/**
 * Render the branch-target deploy workflow.
 * @param params - Workspace and rendering configuration
 * @returns Rendered YAML and the list of managed job/step ids
 */
export function renderBranchWorkflow(params: RenderBranchParams): RenderResult {
  const { branch } = params;
  const seedValidate = !params.apps && (params.seedValidate ?? false);
  const migrationDriftCheck = !params.apps && (params.migrationDriftCheck ?? false);
  const seed = params.apps ? undefined : params.seed;
  const erdPreview = params.erdPreview;
  const ghes = params.ghes ?? false;
  const migrationTest = params.apps ? undefined : params.migrationTest;

  let out = branchTemplate;
  out = block(out, "PLAN_JOB", true);
  out = block(out, "ERD_PREVIEW_JOB", erdPreview !== null);
  out = block(out, "ERD_PREVIEW_COMMENT_JOB", erdPreview !== null);
  out = block(out, "ERD_GITHUB_COM_UPLOAD", !ghes);
  out = block(out, "ERD_GHES_UPLOAD", ghes);
  out = line(
    out,
    "ERD_COMMENT_NEEDS",
    ghes ? "needs: [tailor-erd-preview-matrix, tailor-erd-preview]" : "needs: tailor-erd-preview",
  );
  out = block(out, "ERD_GITHUB_COM_ACTIONS_READ", !ghes);
  out = block(out, "ERD_GHES_NAMESPACES", ghes);
  out = block(out, "ERD_GITHUB_COM_LINKS", !ghes);
  out = block(out, "ERD_GHES_LINKS", ghes);
  out = block(out, "PULL_REQUEST", true);
  out = block(out, "DISPATCH_INPUTS", true);
  out = block(out, "MIGRATION_TEST_JOB", migrationTest !== undefined);
  out = line(
    out,
    "PR_TYPES",
    migrationTest ? "types: [opened, synchronize, reopened, labeled]" : undefined,
  );
  out = block(out, "SEED_VALIDATE", seedValidate);
  out = block(out, "MIGRATION_DRIFT_CHECK", migrationDriftCheck);
  out = applySeed(out, seed);
  const patterns = changePatterns({
    ...params,
    workflowFile: workflowFilePath("branch", params.workspaceName),
  });
  // A label event reaches the plan and ERD jobs too; only the migration test job reacts to it.
  const pullRequest = migrationTest
    ? "(github.event_name == 'pull_request' && github.event.action != 'labeled')"
    : "github.event_name == 'pull_request'";
  out = line(out, "CHANGES_JOB", patterns ? changesJob(patterns) : undefined);
  out = line(
    out,
    "PLAN_IF",
    gateOnChanges(
      `if: |-\n  ${pullRequest} ||\n  (github.event_name == 'workflow_dispatch' && inputs['dry-run'])`,
      patterns,
    ),
  );
  out = line(out, "ERD_MATRIX_IF", gateOnChanges(`if: ${pullRequest}`, patterns));
  out = line(
    out,
    "DEPLOY_IF",
    gateOnChanges(branchDeployIf(params.restrictDispatch ?? false), patterns),
  );
  out = line(out, "CHANGES_GUARD", changesGuard(patterns));

  if (migrationTest) {
    out = out.replace(
      "name: tailor-result (__WORKSPACE_NAME__)",
      `name: "\${{ github.event.action == 'labeled' && 'tailor-result (__WORKSPACE_NAME__) [label]' || 'tailor-result (__WORKSPACE_NAME__)' }}"`,
    );
  }

  out = applyCommon(out, params).replaceAll("__BRANCH__", () => branch);

  if (migrationTest) {
    const migrationTestValues: Record<string, string> = {
      __MIGRATION_TEST_LABEL__: migrationTest.label,
      __MIGRATION_TEST_ENVIRONMENT__: migrationTest.environment ?? params.environment,
      __MIGRATION_TEST_SOURCE_VARIABLE__:
        migrationTest.environment === undefined
          ? "TAILOR_PLATFORM_WORKSPACE_ID"
          : "TAILOR_PLATFORM_MIGRATION_TEST_SOURCE_WORKSPACE_ID",
    };
    out = out.replaceAll(
      /__MIGRATION_TEST_(?:LABEL|ENVIRONMENT|SOURCE_VARIABLE)__/g,
      (marker) => migrationTestValues[marker]!,
    );
  }

  const generatedIds: string[] = [
    ...changesIds(patterns),
    "tailor-plan",
    ...changesGuardIds("tailor-plan", patterns),
    "tailor-plan/tailor-checkout",
    "tailor-plan/tailor-setup",
    "tailor-plan/tailor-install",
    ...generateCheckIds("tailor-plan", params.apps),
  ];
  generatedIds.push(...seedValidateIds("tailor-plan", seedValidate, params.apps));
  generatedIds.push("tailor-plan/tailor-drift-check");
  generatedIds.push(...migrationDriftCheckIds("tailor-plan", migrationDriftCheck, params.apps));
  generatedIds.push("tailor-plan/tailor-plan");
  if (erdPreview) {
    generatedIds.push(
      "tailor-erd-preview-matrix",
      ...changesGuardIds("tailor-erd-preview-matrix", patterns),
      "tailor-erd-preview-matrix/tailor-checkout",
      "tailor-erd-preview-matrix/tailor-checkout-base",
      "tailor-erd-preview-matrix/tailor-erd-preview-matrix",
      "tailor-erd-preview",
      "tailor-erd-preview/tailor-checkout",
      "tailor-erd-preview/tailor-setup",
      "tailor-erd-preview/tailor-install",
      "tailor-erd-preview/tailor-checkout-base",
      "tailor-erd-preview/tailor-detect-base-package-manager",
      "tailor-erd-preview/tailor-setup-base-pnpm",
      "tailor-erd-preview/tailor-setup-base-node",
      "tailor-erd-preview/tailor-setup-base-yarn",
      "tailor-erd-preview/tailor-setup-base-bun",
      "tailor-erd-preview/tailor-install-base",
      "tailor-erd-preview/tailor-restore-head-setup",
      "tailor-erd-preview/tailor-build-erd-preview",
      "tailor-erd-preview/tailor-upload-erd-viewer",
      "tailor-erd-preview-comment",
      "tailor-erd-preview-comment/tailor-comment-erd-preview",
    );
  }
  if (migrationTest) {
    generatedIds.push(
      "tailor-migration-test",
      "tailor-migration-test/tailor-checkout",
      "tailor-migration-test/tailor-setup",
      "tailor-migration-test/tailor-install",
      "tailor-migration-test/tailor-migration-test-login",
      "tailor-migration-test/tailor-migration-test",
      "tailor-migration-test/tailor-migration-test-unlabel",
    );
  }
  generatedIds.push(
    "tailor-deploy",
    ...changesGuardIds("tailor-deploy", patterns),
    "tailor-deploy/tailor-checkout",
    "tailor-deploy/tailor-setup",
    "tailor-deploy/tailor-install",
    ...seedValidateIds("tailor-deploy", seed !== undefined, undefined),
    "tailor-deploy/tailor-apply",
    ...seedIds("tailor-deploy", seed),
    "tailor-deploy/tailor-slack-prereq",
    "tailor-deploy/tailor-notify",
  );

  return appendResultJob({ content: out, generatedIds }, "tailor-result");
}

/**
 * Render the tag-target deploy workflow.
 *
 * When `branch` is set, a tag-reachability guard job is generated and the plan
 * job gates on it; otherwise no guard is emitted and tags deploy unconditionally.
 * @param params - Workspace and rendering configuration
 * @returns Rendered YAML and the list of managed job/step ids
 */
export function renderTagWorkflow(params: RenderTagParams): RenderResult {
  const { tagPattern, branch } = params;
  const hasGuard = branch !== undefined;
  const seedValidate = !params.apps && (params.seedValidate ?? false);
  const migrationDriftCheck = !params.apps && (params.migrationDriftCheck ?? false);
  const seed = params.apps ? undefined : params.seed;

  let out = tagTemplate;
  out = block(out, "TAG_GUARD_JOB", hasGuard);
  out = block(out, "SEED_VALIDATE", seedValidate);
  out = block(out, "MIGRATION_DRIFT_CHECK", migrationDriftCheck);
  out = applySeed(out, seed);
  out = line(out, "PLAN_NEEDS", hasGuard ? "needs: tailor-tag-guard" : undefined);
  out = line(
    out,
    "PLAN_IF",
    hasGuard
      ? `if: |-\n  github.event_name == 'workflow_dispatch' ||\n  needs.tailor-tag-guard.outputs.on-branch == 'true'`
      : undefined,
  );
  const deployGate = tagDeployGate(hasGuard, params.restrictDispatch ?? false);
  out = line(out, "DEPLOY_NEEDS", deployGate.needs);
  out = line(out, "DEPLOY_IF", deployGate.if);

  out = applyCommon(out, params).replaceAll("__TAG_PATTERN__", () => tagPattern);
  if (hasGuard) {
    out = out.replaceAll("__BRANCH__", () => branch);
  }

  const generatedIds: string[] = [];
  if (hasGuard) {
    generatedIds.push(
      "tailor-tag-guard",
      "tailor-tag-guard/tailor-checkout",
      "tailor-tag-guard/tailor-tag-guard",
    );
  }
  generatedIds.push(
    "tailor-plan",
    "tailor-plan/tailor-checkout",
    "tailor-plan/tailor-setup",
    "tailor-plan/tailor-install",
    ...generateCheckIds("tailor-plan", params.apps),
    ...seedValidateIds("tailor-plan", seedValidate, params.apps),
    "tailor-plan/tailor-drift-check",
    ...migrationDriftCheckIds("tailor-plan", migrationDriftCheck, params.apps),
  );
  generatedIds.push(
    "tailor-plan/tailor-plan",
    "tailor-deploy",
    "tailor-deploy/tailor-checkout",
    "tailor-deploy/tailor-setup",
    "tailor-deploy/tailor-install",
    "tailor-deploy/tailor-apply",
    ...seedIds("tailor-deploy", seed),
    "tailor-deploy/tailor-slack-prereq",
    "tailor-deploy/tailor-notify",
  );

  return { content: out, generatedIds };
}

/**
 * Render the preview workflow (PR open/sync/close triggers).
 *
 * The deploy job runs on opened/synchronize/reopened events, plus ready_for_review
 * when `ready` is required; the cleanup job runs on the closed event.  Both jobs
 * run in the same workflow so PR number context is always available.
 * @param params - Workspace and rendering configuration
 * @returns Rendered YAML and the list of managed job/step ids
 */
export function renderPreviewWorkflow(params: RenderPreviewParams): RenderResult {
  const { branch } = params;
  const requireLabel = params.require === "label";
  const requireReady = params.require === "ready";
  const seed = params.apps ? undefined : params.seed;

  let out = previewTemplate;
  out = applySeed(out, seed);

  // PR trigger event types — single line() marker avoids duplicate YAML map keys in the template.
  const types = [
    requireLabel ? "labeled" : "opened",
    "synchronize",
    "reopened",
    ...(requireReady ? ["ready_for_review"] : []),
    "closed",
  ];
  out = line(out, "PR_TYPES", `types: [${types.join(", ")}]`);

  // Deploy job if condition. Fork PRs don't have access to secrets/vars, so guard them out.
  const deployConditions = [
    ...(requireLabel
      ? ["contains(github.event.pull_request.labels.*.name, 'tailor:preview')"]
      : []),
    "github.event.action != 'closed'",
    ...(requireReady ? ["!github.event.pull_request.draft"] : []),
    "!github.event.pull_request.head.repo.fork",
  ];
  const deployIf = `if: |-\n  ${deployConditions.join(" &&\n  ")}`;
  const patterns = changePatterns({
    ...params,
    workflowFile: workflowFilePath("preview", params.workspaceName),
  });
  out = line(out, "CHANGES_JOB", patterns ? changesJob(patterns) : undefined);
  out = line(out, "DEPLOY_IF", gateOnChanges(deployIf, patterns));
  out = line(out, "CHANGES_GUARD", changesGuard(patterns));

  // Cleanup always runs on closed regardless of current labels: the label may have been
  // removed after a preview deploy, and the cleanup action is a no-op when no workspace exists.
  // Fork PRs also need guarding since cleanup requires secrets/vars.
  out = line(
    out,
    "CLEANUP_IF",
    `if: |-\n  github.event.action == 'closed' &&\n  !github.event.pull_request.head.repo.fork`,
  );

  out = applyCommon(out, params)
    .replaceAll("__BRANCH__", () => branch)
    .replaceAll("__REGION__", () => params.region);

  const generatedIds: string[] = [
    ...changesIds(patterns),
    "tailor-preview-deploy",
    ...changesGuardIds("tailor-preview-deploy", patterns),
    "tailor-preview-deploy/tailor-checkout",
    "tailor-preview-deploy/tailor-setup",
    "tailor-preview-deploy/tailor-install",
    ...generateCheckIds("tailor-preview-deploy", params.apps),
    "tailor-preview-deploy/tailor-drift-check",
    "tailor-preview-deploy/tailor-preview-deploy",
    ...seedIds("tailor-preview-deploy", seed),
    "tailor-preview-deploy/tailor-preview-comment",
    "tailor-preview-cleanup",
    "tailor-preview-cleanup/tailor-checkout",
    "tailor-preview-cleanup/tailor-setup",
    "tailor-preview-cleanup/tailor-install",
    "tailor-preview-cleanup/tailor-preview-cleanup",
  ];

  return appendResultJob({ content: out, generatedIds }, "tailor-preview-result");
}

export const AUTOFIX_PROVIDERS = ["github-token", "autofix-ci", "securefix", "github-app"] as const;

/** What commits the regenerated files to the pull request branch. */
export type AutofixProvider = (typeof AUTOFIX_PROVIDERS)[number];

export const AUTOFIX_WORKFLOW_FILE = ".github/workflows/tailor-autofix.yml";

const AUTOFIX_COMMIT_MESSAGE = "chore: run tailor generate";

// autofix.ci and a default securefix server accept requests only from workflows of these names.
const AUTOFIX_WORKFLOW_NAMES: Record<AutofixProvider, string> = {
  "github-token": "Tailor Autofix",
  "autofix-ci": "autofix.ci",
  securefix: "securefix",
  "github-app": "Tailor Autofix",
};

/** A provider, with the settings it needs. */
export type AutofixProviderParams =
  | { provider: Exclude<AutofixProvider, "securefix"> }
  | {
      provider: "securefix";
      /** Name of the repository, under the same owner, that runs the securefix server workflow. */
      securefixServerRepository: string;
    };

export type RenderAutofixParams = AutofixProviderParams & {
  /** App directories relative to the repository root; `tailor generate` runs in each. */
  dirs: readonly string[];
  packageManager: PackageManager;
};

function perAppGenerateSteps(dirs: readonly string[]): string {
  return dirs
    .flatMap((dir) => [
      `- id: tailor-generate-${appSlug(dir)}`,
      `  run: __TAILOR_CLI__ generate`,
      ...(dir === "." ? [] : [`  working-directory: ${dir}`]),
    ])
    .join("\n");
}

/**
 * Render the workflow that commits the files `tailor generate` changes to the pull request.
 * @param params - Provider, app directories, and package manager
 * @returns Rendered YAML and the list of managed job/step ids
 */
export function renderAutofixWorkflow(params: RenderAutofixParams): RenderResult {
  const { provider, dirs, packageManager } = params;
  const multi = dirs.length > 1;
  const hasPushJob = provider === "github-token" || provider === "github-app";
  const workingDirectory = !multi && dirs[0] !== "." ? dirs[0] : undefined;

  let out = line(autofixTemplate, "HEADER", HEADER);
  out = line(
    out,
    "AUTOFIX_IF",
    provider === "autofix-ci"
      ? undefined
      : "if: |-\n  github.event.pull_request.head.repo.full_name == github.repository &&\n  github.actor != 'dependabot[bot]'",
  );
  out = block(out, "GENERATE", !multi);
  out = line(out, "PER_APP_GENERATE", multi ? perAppGenerateSteps(dirs) : undefined);
  out = line(
    out,
    "WORKING_DIRECTORY",
    workingDirectory ? `working-directory: ${workingDirectory}` : undefined,
  );
  out = block(out, "PATCH_OUTPUTS", hasPushJob);
  out = block(out, "RESTORE_PATCH", !hasPushJob);
  out = block(out, "UPLOAD_PATCH", hasPushJob);
  out = block(out, "PUSH_JOB", hasPushJob);
  out = block(out, "APP_TOKEN", provider === "github-app");
  out = block(out, "AUTOFIX_CI", provider === "autofix-ci");
  out = block(out, "SECUREFIX", provider === "securefix");
  out = out
    .replaceAll("__WORKFLOW_NAME__", AUTOFIX_WORKFLOW_NAMES[provider])
    .replaceAll("__PUSH_CONTENTS_PERMISSION__", provider === "github-token" ? "write" : "read")
    .replaceAll(
      "__PUSH_TOKEN__",
      provider === "github-app"
        ? "${{ steps.tailor-app-token.outputs.token }}"
        : "${{ github.token }}",
    )
    .replaceAll("__COMMIT_MESSAGE__", AUTOFIX_COMMIT_MESSAGE)
    .replaceAll("__PACKAGE_MANAGER__", packageManager)
    .replaceAll("__TAILOR_CLI__", TAILOR_CLI_COMMANDS[packageManager]);
  if (params.provider === "securefix") {
    out = out.replaceAll("__SECUREFIX_SERVER_REPOSITORY__", () => params.securefixServerRepository);
  }

  const generatedIds = [
    "tailor-autofix",
    "tailor-autofix/tailor-checkout",
    "tailor-autofix/tailor-setup",
    "tailor-autofix/tailor-install",
    "tailor-autofix/tailor-autofix-baseline",
    ...(multi
      ? dirs.map((dir) => `tailor-autofix/tailor-generate-${appSlug(dir)}`)
      : ["tailor-autofix/tailor-generate"]),
    "tailor-autofix/tailor-autofix-diff",
  ];
  if (hasPushJob) {
    generatedIds.push(
      "tailor-autofix/tailor-upload-patch",
      "tailor-autofix-push",
      ...(provider === "github-app" ? ["tailor-autofix-push/tailor-app-token"] : []),
      "tailor-autofix-push/tailor-checkout",
      "tailor-autofix-push/tailor-download-patch",
      "tailor-autofix-push/tailor-commit",
    );
  } else if (provider === "autofix-ci") {
    generatedIds.push("tailor-autofix/tailor-autofix-ci-auth", "tailor-autofix/tailor-autofix-ci");
  } else {
    generatedIds.push("tailor-autofix/tailor-securefix");
  }

  return { content: out, generatedIds };
}


const HEADER = `# Generated by \`tailor setup\` — managed by the Tailor SDK.
#
# - The SDK manages the jobs and steps whose id starts with \`tailor-\` and the
#   top-level name, on, and permissions. Do not edit or rename them:
#   \`tailor setup check\` reports it, and re-running \`tailor setup\` then needs
#   --force.
# - Give the jobs and steps you add ids that do not start with \`tailor-\`:
#   the prefix is reserved for the SDK, and \`tailor setup\` stops on it.
# - Re-running \`tailor setup\` keeps your own jobs and steps, every other
#   top-level key, and runs-on, timeout-minutes, container, and env on managed
#   jobs and the ignore, fail-on-drift, install-command, node-version-file,
#   label, and user-mapping inputs of managed steps.
# - State is tracked in .github/tailor.lock (machine-owned: commit it; the only
#   part to edit by hand is appIds, to re-key an app after moving its directory).`;


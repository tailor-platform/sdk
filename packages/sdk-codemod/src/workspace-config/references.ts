import * as path from "pathe";
import { findImportStatements, importSource } from "../ast-grep-helpers";
import { SOURCE_EXTENSIONS } from "../walk-files";
import {
  literalText,
  moduleCandidates,
  relativeSpecifier,
  type ModuleCache,
  type Report,
} from "./project";
import { applyEdits, replaceNode, type TextEdit } from "./text";
import type { ConfigPathUse } from "./groups";
import type { SgNode } from "@ast-grep/napi";

const GENERATED_TYPES_HEADER = "// This file is auto-generated by @tailor-platform/sdk";

/** What the conversion changes or reports outside the merged configs. */
export type ReferenceChanges = {
  writes: Record<string, string>;
  deletes: string[];
  warnings: string[];
  findings: Report[];
};

function specifierFor(fromPath: string, outputPath: string, original: string): string {
  const extension = /\.[cm]?[jt]sx?$/u.exec(original)?.[0];
  const target = outputPath.replace(/\.[cm]?[jt]sx?$/u, extension ?? "");
  return relativeSpecifier(fromPath, target);
}

/** The top-level imports and re-exports of a module that name another module. */
function moduleReferences(root: SgNode): SgNode[] {
  return [
    ...findImportStatements(root),
    ...root
      .children()
      .filter(
        (statement) =>
          statement.kind() === "export_statement" &&
          statement.children().some((child) => child.kind() === "string"),
      ),
  ];
}

/** Whether a reference takes the module's default export, its namespace, or every export. */
function takesWholeModule(statement: SgNode): boolean {
  if (statement.kind() === "export_statement") {
    return !statement.children().some((child) => child.kind() === "export_clause");
  }
  const clause = statement.children().find((child) => child.kind() === "import_clause");
  return (
    clause
      ?.children()
      .some((child) => child.kind() === "identifier" || child.kind() === "namespace_import") ??
    false
  );
}

/**
 * Point the project at the workspace config instead of the configs merged into it: rewrite
 * imports of a merged config, delete the type definitions generated next to it, and report the
 * scripts, workflows, and code that name it.
 * @param cache - Module cache of the project
 * @param merged - Project-relative paths of the deleted configs
 * @param outputPath - Project-relative path of the workspace config
 * @param uses - Where scripts and workflows name config paths
 * @param managedWorkflows - Project-relative paths of the workflows `tailor setup ci` generated, which it regenerates
 * @returns The changes
 */
export function redirectReferences(
  cache: ModuleCache,
  merged: readonly string[],
  outputPath: string,
  uses: readonly ConfigPathUse[],
  managedWorkflows: ReadonlySet<string>,
): ReferenceChanges {
  const changes: ReferenceChanges = { writes: {}, deletes: [], warnings: [], findings: [] };
  const deleted = new Set(merged);
  for (const file of cache.project.paths) {
    if (deleted.has(file) || file === outputPath || !SOURCE_EXTENSIONS.has(path.extname(file))) {
      continue;
    }
    const module = cache.get(file);
    if (!module) continue;
    const edits: TextEdit[] = [];
    const references = moduleReferences(module.root);
    for (const statement of references) {
      const specifier = importSource(statement);
      const resolved = specifier === null ? null : cache.resolve(file, specifier);
      if (resolved === null || !deleted.has(resolved)) continue;
      if (takesWholeModule(statement)) {
        changes.findings.push({
          file,
          node: statement,
          message: `This takes the whole module of ${resolved}, which the conversion merged into ${outputPath}.`,
        });
        continue;
      }
      const literal = statement.children().find((child) => child.kind() === "string")!;
      const quote = literal.text()[0];
      edits.push(
        replaceNode(literal, `${quote}${specifierFor(file, outputPath, specifier!)}${quote}`),
      );
    }
    const ranges = references.map((statement) => statement.range());
    for (const node of module.root.findAll({
      rule: { any: [{ kind: "string" }, { kind: "template_string" }] },
    })) {
      const text = literalText(node);
      if (text === null || !/[./]/u.test(text)) continue;
      const start = node.range().start.index;
      if (ranges.some((range) => range.start.index <= start && start < range.end.index)) continue;
      const named = [path.join(path.dirname(file), text), path.normalize(text)]
        .flatMap(moduleCandidates)
        .find((candidate) => deleted.has(candidate));
      if (named === undefined) continue;
      changes.findings.push({
        file,
        node,
        message: `This names ${named}, which the conversion merged into ${outputPath}.`,
      });
    }
    if (edits.length > 0) changes.writes[file] = applyEdits(module.source, edits);
  }

  for (const use of uses) {
    const named = use.paths.filter((entry) => deleted.has(entry));
    if (named.length === 0 || managedWorkflows.has(use.file)) continue;
    const kind = use.file.endsWith("package.json")
      ? "script"
      : use.file.includes(".github/workflows/")
        ? "workflow"
        : "setting";
    const remedy =
      kind === "workflow"
        ? ` Point it at ${outputPath}, or generate a workflow for the workspace config with \`tailor setup ci\`.`
        : "";
    changes.findings.push({
      file: use.file,
      line: use.line,
      excerpt: use.excerpt,
      message: `This ${kind} names ${named.join(", ")}, which the conversion merged into ${outputPath}.${remedy}`,
    });
  }

  for (const config of merged) {
    const types = path.join(path.dirname(config), "tailor.d.ts");
    if (cache.project.read(types)?.startsWith(GENERATED_TYPES_HEADER)) changes.deletes.push(types);
    const context = path.join(
      path.dirname(config),
      ".tailor",
      `${path.basename(config)}.context.json`,
    );
    if (cache.project.exists(context)) {
      changes.warnings.push(
        `${config}: the workspace that \`tailor deploy\` saved for this config does not carry over to ${outputPath}; pass --workspace-id or choose the workspace again on the next deploy.`,
      );
    }
  }
  return changes;
}

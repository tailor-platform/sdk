import { describe, expect, test } from "vitest";
import { createProject, runOnProject } from "./test-helpers/project";

const CODEMODS = ["v3/config-to-app", "v3/config-to-workspace"];
const TAKEOVER_WARNING =
  "tailor.config.ts: the next `tailor deploy` asks to take over the resources this config deployed before the conversion. Run it where it can prompt, or pass --yes.";

function lines(...source: string[]): string {
  return `${source.join("\n")}\n`;
}

function findingsOf(result: Awaited<ReturnType<typeof runOnProject>>) {
  return result.llmReviews
    .filter((review) => review.codemodId === "v3/config-to-workspace")
    .flatMap((review) => review.findings ?? [])
    .map(({ file, line, message, excerpt }) => ({ file, line, message, excerpt }));
}

const SDK_IMPORT = 'import { defineConfig } from "@tailor-platform/sdk";';

const multiApplication = {
  "package.json": `${JSON.stringify(
    {
      name: "multi-application",
      scripts: {
        deploy: "pnpm run deploy:user && pnpm run deploy:admin",
        "deploy:user": "tailor deploy -c apps/user/tailor.config.ts",
        "deploy:admin": "tailor deploy -c apps/admin/tailor.config.ts",
      },
    },
    null,
    2,
  )}\n`,
  "apps/user/tailor.config.ts": lines(
    SDK_IMPORT,
    "",
    'export const sharedDb = "shared-db";',
    "",
    "export default defineConfig({",
    '  name: "user",',
    "  db: { [sharedDb]: { files: [`./db/**/*.ts`] } },",
    "});",
  ),
  "apps/user/db/user.ts": 'export const user = db.table("User", {});\n',
  "apps/user/tailor.d.ts":
    "// This file is auto-generated by @tailor-platform/sdk\n// Do not edit this file manually\n",
  "apps/admin/tailor.config.ts": lines(
    SDK_IMPORT,
    'import { sharedDb } from "../user/tailor.config";',
    "",
    "export default defineConfig({",
    '  name: "admin",',
    "  db: {",
    "    [sharedDb]: { external: true },",
    '    "admin-db": { files: [`./db/**/*.ts`] },',
    "  },",
    "});",
  ),
  "apps/admin/db/adminNote.ts": 'export const adminNote = db.table("AdminNote", {});\n',
  "apps/admin/resolvers/notes.ts": lines(
    'import { sharedDb } from "../../user/tailor.config";',
    "export const namespace = sharedDb;",
  ),
};

describe("v3/config-to-workspace", () => {
  test("merges the configs of the multi-application template into one workspace config", async () => {
    const project = createProject(multiApplication);

    const result = await runOnProject(CODEMODS, project);

    expect(project.read("tailor.config.ts")).toBe(
      lines(
        'import { defineWorkspace } from "@tailor-platform/sdk";',
        "",
        'export const sharedDb = "shared-db";',
        "",
        "export default defineWorkspace({",
        "  db: {",
        "    [sharedDb]: { files: [`./apps/user/db/**/*.ts`] },",
        '    "admin-db": { files: [`./apps/admin/db/**/*.ts`] },',
        "  },",
        "  apps: {",
        "    user: { db: [sharedDb] },",
        '    admin: { db: [sharedDb, "admin-db"] },',
        "  },",
        "});",
      ),
    );
    expect(result.filesDeleted).toEqual([
      "apps/admin/tailor.config.ts",
      "apps/user/tailor.config.ts",
      "apps/user/tailor.d.ts",
    ]);
    expect(project.read("apps/admin/resolvers/notes.ts")).toBe(
      lines(
        'import { sharedDb } from "../../../tailor.config";',
        "export const namespace = sharedDb;",
      ),
    );
    expect(result.warnings).toEqual([TAKEOVER_WARNING]);
    expect(findingsOf(result).map(({ file, line, message }) => ({ file, line, message }))).toEqual([
      {
        file: "package.json",
        line: 5,
        message:
          "This script names apps/user/tailor.config.ts, which the conversion merged into tailor.config.ts.",
      },
      {
        file: "package.json",
        line: 6,
        message:
          "This script names apps/admin/tailor.config.ts, which the conversion merged into tailor.config.ts.",
      },
    ]);

    const rerun = await runOnProject(CODEMODS, project);
    expect(rerun.filesModified).toEqual([]);
    expect(rerun.filesDeleted).toEqual([]);
  });

  test("renames clashing declarations and names the Auth service where the merge makes a machine user ambiguous", async () => {
    const project = createProject({
      "package.json": `${JSON.stringify({ scripts: { deploy: "tailor deploy -c apps/a/tailor.config.ts,apps/b/tailor.config.ts" } })}\n`,
      "apps/a/tailor.config.ts": lines(
        'import { defineAuth, defineConfig } from "@tailor-platform/sdk";',
        "",
        'const auth = defineAuth("a-auth", { machineUsers: { seeder: {}, admin: {} } });',
        "",
        "export default defineConfig({",
        '  name: "a",',
        "  auth,",
        '  db: { "a-db": { files: ["./db/*.ts"], migration: { directory: "./migrations" } } },',
        "});",
      ),
      "apps/b/tailor.config.ts": lines(
        'import { defineAuth, defineConfig } from "@tailor-platform/sdk";',
        "",
        'const auth = defineAuth("b-auth", { machineUsers: { admin: {} } });',
        "",
        "export default defineConfig({",
        '  name: "b",',
        "  auth: auth,",
        '  executor: { files: ["./executors/*.ts"] },',
        "});",
      ),
      "apps/b/executors/sync.ts": lines(
        'import { createExecutor, scheduleTrigger } from "@tailor-platform/sdk";',
        "",
        "export default createExecutor({",
        '  name: "sync",',
        '  trigger: scheduleTrigger({ cron: "0 * * * *" }),',
        '  operation: { kind: "function", body: () => {}, invoker: "admin" },',
        "});",
      ),
    });

    const result = await runOnProject(CODEMODS, project);

    expect(project.read("tailor.config.ts")).toBe(
      lines(
        'import { defineAuth, defineWorkspace } from "@tailor-platform/sdk";',
        "",
        'const auth = defineAuth("a-auth", { machineUsers: { seeder: {}, admin: {} } });',
        "",
        'const bAuth = defineAuth("b-auth", { machineUsers: { admin: {} } });',
        "",
        "export default defineWorkspace({",
        '  db: { "a-db": { files: ["./apps/a/db/*.ts"], migration: { directory: "./apps/a/migrations", machineUser: "seeder" } } },',
        '  executor: { files: ["./apps/b/executors/*.ts"] },',
        "  auth: { [auth.name]: auth, [bAuth.name]: bAuth },",
        "  apps: {",
        '    a: { db: ["a-db"], auth: auth.name },',
        "    b: { auth: bAuth.name },",
        "  },",
        "});",
      ),
    );
    expect(project.read("apps/b/executors/sync.ts")).toContain(
      'invoker: { namespace: "b-auth", machineUserName: "admin" } },',
    );
    expect(findingsOf(result).map(({ file, message }) => ({ file, message }))).toEqual([
      {
        file: "package.json",
        message:
          "This script names apps/a/tailor.config.ts, apps/b/tailor.config.ts, which the conversion merged into tailor.config.ts.",
      },
    ]);
  });

  test("merges env and reports a key only some configs set", async () => {
    const project = createProject({
      "package.json": `${JSON.stringify({ scripts: { deploy: "tailor deploy -c a/tailor.config.ts,b/tailor.config.ts" } })}\n`,
      "a/tailor.config.ts": lines(
        SDK_IMPORT,
        'export default defineConfig({ name: "a", env: { APP_ENV: "dev", A_ONLY: "1" }, db: { a: { files: [] } } });',
      ),
      "b/tailor.config.ts": lines(
        SDK_IMPORT,
        'export default defineConfig({ name: "b", env: { APP_ENV: "dev" }, db: { b: { files: [] } } });',
      ),
    });

    const result = await runOnProject(CODEMODS, project);

    expect(project.read("tailor.config.ts")).toContain(
      lines("  env: {", '    APP_ENV: "dev",', '    A_ONLY: "1",', "  },"),
    );
    expect(result.warnings).toContain(
      "tailor.config.ts: env key A_ONLY, which only a/tailor.config.ts set, now reaches every function of the workspace.",
    );
  });

  test("leaves the configs when they set one env key to different values, without printing the values", async () => {
    const files = {
      "package.json": `${JSON.stringify({ scripts: { deploy: "tailor deploy -c a/tailor.config.ts,b/tailor.config.ts" } })}\n`,
      "a/tailor.config.ts": lines(
        SDK_IMPORT,
        'export default defineConfig({ name: "a", env: { API_URL: "https://a.example.com" }, db: { a: { files: [] } } });',
      ),
      "b/tailor.config.ts": lines(
        SDK_IMPORT,
        'export default defineConfig({ name: "b", env: { API_URL: "https://b.example.com" }, db: { b: { files: [] } } });',
      ),
    };
    const project = createProject(files);

    const result = await runOnProject(CODEMODS, project);

    expect(project.files()).toEqual(Object.keys(files).toSorted());
    expect(project.read("a/tailor.config.ts")).toBe(files["a/tailor.config.ts"]);
    expect(findingsOf(result)).toEqual([
      {
        file: "b/tailor.config.ts",
        line: 2,
        message:
          "The configs set env key API_URL differently (a/tailor.config.ts, b/tailor.config.ts), so they were not merged. A workspace config has one root value per key, which a resolver namespace, the executors, the workflows, or an Auth service can override.",
        excerpt: "API_URL",
      },
    ]);
    expect(JSON.stringify(result)).not.toContain("example.com");
  });

  test("leaves configs deployed together when one uses a service none of them defines", async () => {
    const files = {
      "package.json": `${JSON.stringify({ scripts: { deploy: "tailor deploy -c a/tailor.config.ts,b/tailor.config.ts" } })}\n`,
      "a/tailor.config.ts": lines(
        SDK_IMPORT,
        'export default defineConfig({ name: "a", db: { a: { files: [] } } });',
      ),
      "b/tailor.config.ts": lines(
        SDK_IMPORT,
        'export default defineConfig({ name: "b", db: { shared: { external: true } } });',
      ),
    };
    const project = createProject(files);

    const result = await runOnProject(CODEMODS, project);

    expect(project.files()).toEqual(Object.keys(files).toSorted());
    expect(findingsOf(result).map(({ file, message }) => ({ file, message }))).toEqual([
      {
        file: "b/tailor.config.ts",
        message:
          'The db namespace "shared" is external, but no config in this project defines it, so the config was not converted.',
      },
    ]);
  });

  test("points the setup targets and the lock at the workspace config", async () => {
    const project = createProject({
      ...multiApplication,
      ".github/tailor.lock": `${JSON.stringify(
        {
          version: 2,
          targets: [
            {
              kind: "branch",
              workspaceName: "shop",
              inputs: {
                dir: ".",
                environment: "shop",
                apps: [
                  { dir: "apps/user", migrationDriftCheck: true },
                  { dir: "apps/admin", seedValidate: false },
                ],
              },
            },
          ],
          appIds: {
            "apps/user/tailor.config.ts": "8b1f4c1e-2f6a-4c55-9a43-5d1f0c3e7a21",
            "apps/admin/tailor.config.ts": "0c6a5b0e-6d42-4b1e-9f0b-0a8b2d6c3e44",
          },
        },
        null,
        2,
      )}\n`,
    });

    const result = await runOnProject(CODEMODS, project);

    expect(JSON.parse(project.read(".github/tailor.lock")!)).toEqual({
      version: 3,
      targets: [
        {
          kind: "branch",
          workspaceName: "shop",
          inputs: { dir: ".", environment: "shop", migrationDriftCheck: true },
        },
      ],
      appIds: {},
      workspaces: ["tailor.config.ts"],
    });
    expect(result.warnings).toContain(
      ".github/tailor.lock: the branch shop workflow now deploys tailor.config.ts. Run `tailor setup ci update` to regenerate it.",
    );
  });
});

#!/usr/bin/env node

import { fileURLToPath } from "node:url";
import {
  annotateTerminalError,
  errorToJson,
  serializeError,
  createCommonArgs,
  loadEnvFilesFromArgv,
  logger,
  defineCommand,
  runMain,
} from "@tailor-platform/sdk/cli";
import * as path from "pathe";
import { readPackageJSON } from "pkg-types";
import { z } from "zod";
import { seedApplyCommand } from "./apply";
import { seedDumpCommand } from "./dump";
import { seedFillCommand } from "./fill";
import { seedValidateCommand } from "./validate";

function formattedText(error: unknown): string | undefined {
  if (typeof error !== "object" || error === null) return undefined;
  const format = (error as { format?: unknown }).format;
  if (typeof format !== "function") return undefined;
  const formatted: unknown = format.call(error);
  return typeof formatted === "string" ? formatted : undefined;
}

/**
 * Prefix a failure's message with the file it points at, as the host CLI prints it.
 * @param error - Failure to print
 * @returns The message of the failure's JSON error envelope
 */
function locatedMessage(error: Error): string {
  const { message } = errorToJson(error).error;
  return typeof message === "string" ? message : error.message;
}

const packageRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = await readPackageJSON(packageRoot);

const mainCommand = defineCommand({
  name: "tailor-seed",
  description:
    "Seed TailorDB and IdP data from JSONL files generated by seedPlugin, and dump the current data back out.\n" +
    "Tailor CLI plugin: installed alongside the Tailor CLI, it runs as `tailor seed <command>`.",
  subCommands: {
    apply: seedApplyCommand,
    dump: seedDumpCommand,
    validate: seedValidateCommand,
    fill: seedFillCommand,
  },
});

// -v matches the generated seed runner this plugin replaces
// Mirrored in KNOWN_PLUGIN_COMMON_ARGS_OPTIONS (packages/sdk/src/cli/shared/plugin.ts)
const commonArgsOptions = { verboseAlias: "v" };

void runMain(mainCommand, {
  version: packageJson.version ?? "0.0.0",
  globalArgs: z.strictObject(createCommonArgs(commonArgsOptions)),
  displayErrors: false,
  setup: () => loadEnvFilesFromArgv(process.argv.slice(2), commonArgsOptions),
  cleanup: ({ error }) => {
    if (!error) return;
    const formatted = formattedText(error);
    if (logger.jsonMode) {
      logger.log(serializeError(error, { includeStack: logger.verbose }));
    } else if (formatted !== undefined) {
      logger.log(formatted);
    } else if (error instanceof Error) {
      logger.error(locatedMessage(error));
    } else {
      logger.error(`Unknown error: ${String(error)}`);
    }
    if (!logger.jsonMode && error instanceof Error && error.stack) {
      logger.debug(`\nStack trace:\n${error.stack}`);
    }
    annotateTerminalError(error, { jsonMode: logger.jsonMode });
  },
});

#!/usr/bin/env node

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..");
const configPath = resolve(repoRoot, ".agents/rules.json");
const agentsPath = resolve(repoRoot, "AGENTS.md");
const claudeRulesDir = resolve(repoRoot, ".claude/rules");

const startMarker = "<!-- agent-rules:start -->";
const endMarker = "<!-- agent-rules:end -->";
const generatedComment =
  "<!-- This block is generated by `pnpm agent:rules:update`. Edit `.agents/rules.json` and `.agents/rules/*.md` instead. -->";

const mode = parseMode(process.argv.slice(2));

function parseMode(args) {
  const modes = args.filter((arg) => arg === "--check" || arg === "--write");
  if (modes.length !== 1 || modes.length !== args.length) {
    console.error("Usage: node scripts/sync-agent-rules.mjs --check|--write");
    process.exit(2);
  }
  return modes[0] === "--write" ? "write" : "check";
}

function repoRelative(file) {
  return relative(repoRoot, file).split(sep).join("/");
}

function ensureString(value, context) {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${context} must be a non-empty string`);
  }
  return value;
}

function ensureStringArray(value, context) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error(`${context} must be a non-empty array`);
  }
  return value.map((entry, index) => ensureString(entry, `${context}[${index}]`));
}

function parseRuleTitle(body, file) {
  const match = body.match(/^#\s+(.+)$/m);
  if (!match) {
    throw new Error(`${file} must contain a top-level Markdown heading`);
  }
  return match[1].trim();
}

function assertNoFrontmatter(body, file) {
  if (body.startsWith("---\n")) {
    throw new Error(
      `${file} must not contain frontmatter. Put path scopes in .agents/rules.json instead.`,
    );
  }
}

function quoteYaml(value) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function buildClaudeRule(paths, body) {
  const frontmatter = [
    "---",
    "paths:",
    ...paths.map((path) => `  - ${quoteYaml(path)}`),
    "---",
    "",
    "",
  ];
  return `${frontmatter.join("\n")}${body.endsWith("\n") ? body : `${body}\n`}`;
}

function buildAgentsRuleIndex(rules) {
  const rows = rules.map((rule) => {
    const paths = rule.paths.map((path) => `\`${path}\``).join(", ");
    return `- ${paths}: [${rule.title}](${rule.file})`;
  });
  return [startMarker, generatedComment, "", ...rows, "", endMarker].join("\n");
}

function replaceGeneratedBlock(content, replacement) {
  const start = content.indexOf(startMarker);
  const end = content.indexOf(endMarker);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`AGENTS.md must contain ${startMarker} and ${endMarker}`);
  }
  return `${content.slice(0, start)}${replacement}${content.slice(end + endMarker.length)}`;
}

async function readRules() {
  const raw = JSON.parse(await readFile(configPath, "utf-8"));
  if (!Array.isArray(raw.rules)) {
    throw new Error(".agents/rules.json must contain a rules array");
  }

  const names = new Set();
  const rules = [];
  for (const [index, entry] of raw.rules.entries()) {
    const context = `.agents/rules.json rules[${index}]`;
    const name = ensureString(entry.name, `${context}.name`);
    if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) {
      throw new Error(`${context}.name must use lowercase letters, numbers, and hyphens`);
    }
    if (names.has(name)) {
      throw new Error(`${context}.name duplicates ${name}`);
    }
    names.add(name);

    const paths = ensureStringArray(entry.paths, `${context}.paths`);
    const file = ensureString(entry.file, `${context}.file`);
    const expectedFile = `.agents/rules/${name}.md`;
    if (file !== expectedFile) {
      throw new Error(`${context}.file must be ${expectedFile}`);
    }

    const body = await readFile(resolve(repoRoot, file), "utf-8");
    assertNoFrontmatter(body, file);
    rules.push({
      name,
      paths,
      file,
      title: parseRuleTitle(body, file),
      body,
      claudeFile: resolve(claudeRulesDir, `${name}.md`),
    });
  }
  return rules;
}

async function listStaleClaudeRuleFiles(expectedFiles) {
  let entries = [];
  try {
    entries = await readdir(claudeRulesDir, { withFileTypes: true });
  } catch (err) {
    if (err.code === "ENOENT") return [];
    throw err;
  }
  return entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
    .map((entry) => resolve(claudeRulesDir, entry.name))
    .filter((file) => !expectedFiles.has(file));
}

async function main() {
  const rules = await readRules();
  const agentsContent = await readFile(agentsPath, "utf-8");
  const expectedAgentsContent = replaceGeneratedBlock(agentsContent, buildAgentsRuleIndex(rules));

  const expectedClaudeRules = new Map(
    rules.map((rule) => [rule.claudeFile, buildClaudeRule(rule.paths, rule.body)]),
  );
  const staleClaudeRules = await listStaleClaudeRuleFiles(expectedClaudeRules);

  if (mode === "write") {
    await writeFile(agentsPath, expectedAgentsContent);
    await mkdir(claudeRulesDir, { recursive: true });
    for (const [file, content] of expectedClaudeRules) {
      await writeFile(file, content);
    }
    for (const file of staleClaudeRules) {
      await rm(file);
    }
    console.log(
      `Generated AGENTS.md rule index and ${expectedClaudeRules.size} Claude rule adapter(s).`,
    );
    return;
  }

  const drift = [];
  if (agentsContent !== expectedAgentsContent) {
    drift.push("AGENTS.md");
  }
  for (const [file, expected] of expectedClaudeRules) {
    let actual = "";
    try {
      actual = await readFile(file, "utf-8");
    } catch (err) {
      if (err.code === "ENOENT") {
        drift.push(repoRelative(file));
        continue;
      }
      throw err;
    }
    if (actual !== expected) {
      drift.push(repoRelative(file));
    }
  }
  drift.push(...staleClaudeRules.map(repoRelative));

  if (drift.length > 0) {
    console.error("Agent rule generated files are out of date:");
    for (const file of drift) {
      console.error(`  - ${file}`);
    }
    console.error("\nRun `pnpm agent:rules:update` and commit the result.");
    process.exit(1);
  }

  console.log(`Checked ${rules.length} agent rule(s): generated files are up to date.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
